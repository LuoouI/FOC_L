/***********************************************
 * @brief : 查询正弦定标值
 * @param : Angle 电角度，0~32767对应0~2PI
 * @return: 正弦定标值，范围-10000~10000
 * @date  : 2026-08-15
 * @author: L
 ************************************************/
static int32 FastSinLookup(uint16 Angle)
{
    uint16 Quadrant;
    uint16 Phase;
    uint16 Index;
    uint16 Fraction;
    int32 Value0;
    int32 Value1;
    int32 Value;

    Angle &= ANGLE_MAX;
    Quadrant = Angle >> 13u;
    Phase = Angle & 0x1FFFu;

    if ((Quadrant & 1u) != 0u)
    {
        Phase = ANGLE_QUARTER_PERIOD - Phase;
    }

    Index = Phase >> FAST_SIN_STEP_SHIFT;
    Fraction = Phase & FAST_SIN_STEP_MASK;
    Value0 = (int32)FastSinQuarterTable[Index];
    Value1 = (Index < FAST_SIN_QUARTER_COUNT) ?
             (int32)FastSinQuarterTable[Index + 1u] : Value0;
    Value = Value0 +
            ((Value1 - Value0) * (int32)Fraction) / FAST_SIN_STEP_SIZE;

    if (Quadrant >= 2u)
    {
        Value = -Value;
    }

    return Value;
}

float fast_sinf(uint16 ElectricalAngle)
{
    return (float)FastSinLookup(ElectricalAngle) / (float)FAST_SIN_SCALE;
}

float fast_cosf(uint16 ElectricalAngle)
{
    return (float)FastSinLookup(
               (uint16)(ElectricalAngle + ANGLE_QUARTER_PERIOD)) /
           (float)FAST_SIN_SCALE;
}
