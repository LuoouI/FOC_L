#ifndef MOTOR_CONTROL_OPEN_LOOP_H
#define MOTOR_CONTROL_OPEN_LOOP_H

#include "zf_common_headfile.h"

/*===========================================================================*/
/*  开环控制状态                                                              */
/*===========================================================================*/
typedef struct
{
    float Uq;                   /* 开环q轴电压指令，单位为V */
    uint16 Angle;               /* 开环电压矢量电角度 */
    int16 Step;                 /* 单周期电角度增量，负值表示反向 */
    uint16 Align_count;         /* 启动定向所需控制周期数 */
    uint16 Hold_count;          /* 启动定向计数 */
    uint8 Started;              /* 开环启动状态 */
} Motor_OpenLoop_t;

/*==================================================== 基础函数 ====================================================*/
void    Open_Loop_Update (float Uq,
                          float Ud,
                          int16 Step);
/*==================================================== 基础函数 ====================================================*/

#endif
